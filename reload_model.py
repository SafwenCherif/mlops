"""Reload the best logged model and predict churn for an example customer."""

import mlflow
import mlflow.sklearn
import pandas as pd

from mlflow_lab import configure_mlflow, get_ranked_runs


def main() -> None:
    configure_mlflow()
    ranked = get_ranked_runs()
    if ranked.empty:
        raise SystemExit("No scored runs found. Run `python train_mlflow.py` first.")

    best = ranked.iloc[0]
    run_id = best["run_id"]
    model = mlflow.sklearn.load_model(f"runs:/{run_id}/model")
    print("Best run:", best["tags.mlflow.runName"], "| id:", run_id)
    print("Model reloaded:", type(model).__name__)
    print("Number of expected variables:", model.n_features_in_)

    # The baseline category for abonnement is Basique, so these are the
    # columns generated by get_dummies(..., drop_first=True) for this dataset.
    customer = pd.DataFrame(
        [
            {
                "age": 35,
                "salaire": 2500,
                "anciennete": 1,
                "consommation": 10,
                "abonnement_Premium": False,
                "abonnement_Standard": True,
            }
        ]
    )
    expected_features = list(model.feature_names_in_)
    missing_features = sorted(set(expected_features) - set(customer.columns))
    if missing_features:
        raise ValueError(f"No values supplied for model features: {missing_features}")

    customer = customer[expected_features]
    prediction = model.predict(customer)[0]
    print("Will the customer leave? ->", "YES" if prediction == 1 else "NO")


if __name__ == "__main__":
    main()
